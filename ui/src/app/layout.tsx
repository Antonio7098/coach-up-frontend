import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { ClerkProvider } from "@clerk/nextjs";
import "./globals.css";
import "../styles/theme.css";
import AuthGuard from "./AuthGuard";
import { devLog } from "../app/api/lib/observability";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const publishableKey = process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY;

  devLog("info", "layout: initializing root layout", {
    hasPublishableKey: !!publishableKey,
    signInUrl: "/sign-in",
    signUpUrl: "/sign-up"
  });

  return (
    <ClerkProvider
      publishableKey={publishableKey}
      signInUrl="/sign-in"
      signUpUrl="/sign-up"
      afterSignInUrl="/coach-min"
      afterSignUpUrl="/coach-min"
    >
      <html lang="en" suppressHydrationWarning>
        <body
          className={`${geistSans.variable} ${geistMono.variable} antialiased`}
        >
          <AuthGuard>
            {children}
          </AuthGuard>

          {process.env.NODE_ENV === 'development' && (
            <div style={{ position: 'fixed', bottom: 0, right: 0, background: 'rgba(0,0,0,0.8)', color: 'white', padding: '4px', fontSize: '10px', zIndex: 9999 }}>
              Layout initialized
            </div>
          )}
        </body>
      </html>
    </ClerkProvider>
  );
}
